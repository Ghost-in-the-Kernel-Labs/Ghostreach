/**
 * DOM-shape fingerprints, used later to group pages into templates.
 *
 * A page's shape is the set of distinct element paths under <body>, written as tag names plus
 * stable-looking class names, e.g.
 *
 *   main/div.grid-row/div.grid-col/table.vitals-table/tbody/tr/th
 *
 * Text, attributes and repeat counts are ignored, so /pokedex/bulbasaur and /pokedex/ivysaur have
 * the same shape even though every name, number and row count differs. Being a set, the shape can
 * be compared with Jaccard similarity when two pages of one template differ a little (one Pokémon
 * has an extra evolution box); the hash is a quick exact-match key.
 * In the page: SELF-CONTAINED: collectShapePaths goes to page.evaluate() whole (readers/shape.ts), so it uses nothing this file imports or declares beside it.
 */
import { createHash } from 'node:crypto';
import { H } from '../heuristics/crawl.js';

export interface Fingerprint {
  /** First 16 hex characters of the SHA-256 of the sorted paths. */
  hash: string;
  /** Sorted, distinct element paths. */
  paths: string[];
}

export interface ShapeOptions {
  maxDepth: number;
  maxPaths: number;
}

export const DEFAULT_SHAPE_OPTIONS: ShapeOptions = { maxDepth: H.SHAPE_MAX_DEPTH, maxPaths: H.SHAPE_MAX_PATHS };

/**
 * Runs inside the page (passed to page.evaluate), so it must be self-contained: no imports and no
 * references to anything outside its own body.
 */
export function collectShapePaths(opts: ShapeOptions): string[] {
  const SKIP = new Set(['script', 'style', 'noscript', 'template', 'link', 'meta']);
  // Only plain, lower-case class names. Digits, underscores and capitals (css-1x2y3z, sc-AxjAm,
  // jsx-123, Google's hashed class names) mark names generated by a build tool, which may change
  // between builds or between pages of one template. CSS-in-JS prefixes are refused outright.
  const STABLE_CLASS = /^[a-z][a-z-]{1,30}$/;
  const GENERATED_PREFIX = /^(sc|css|jsx|emotion|svelte|ng|mui|chakra|tw)-/;
  const paths = new Set<string>();

  function step(el: Element): string {
    const tag = el.localName.toLowerCase();
    const classes = Array.from(el.classList)
      .filter((c) => STABLE_CLASS.test(c) && !GENERATED_PREFIX.test(c))
      .sort()
      .slice(0, 3);
    return classes.length ? `${tag}.${classes.join('.')}` : tag;
  }

  function walk(el: Element, prefix: string, depth: number): void {
    for (const child of Array.from(el.children)) {
      const tag = child.localName.toLowerCase();
      if (SKIP.has(tag)) continue;
      const path = prefix ? `${prefix}/${step(child)}` : step(child);
      paths.add(path);
      // An SVG's inner drawing is artwork, not page structure.
      if (depth + 1 < opts.maxDepth && tag !== 'svg') walk(child, path, depth + 1);
    }
  }

  if (document.body) walk(document.body, '', 0);
  return Array.from(paths).sort().slice(0, opts.maxPaths);
}

export function fingerprintFromPaths(paths: string[]): Fingerprint {
  const sorted = Array.from(new Set(paths)).sort();
  const hash = createHash('sha256').update(sorted.join('\n')).digest('hex').slice(0, 16);
  return { hash, paths: sorted };
}
